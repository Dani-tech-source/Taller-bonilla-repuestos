--Creacion de tabla vacia
-- Modelos compatibles: un repuesto puede encajar en VARIOS modelos
create table repuesto_modelos (
  id bigint generated always as identity primary key,
  repuesto_id bigint not null references repuestos(id) on delete cascade,
  modelo text not null,
  unique (repuesto_id, modelo)
);

-- Seguridad: igual que repuestos, solo lectura pública
alter table repuesto_modelos enable row level security;
grant select on repuesto_modelos to anon, authenticated;
create policy "Compatibilidad pública de lectura"
  on repuesto_modelos for select
  using (true);


